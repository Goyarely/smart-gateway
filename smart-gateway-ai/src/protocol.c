uint16_t crc16(const uint8_t * data, size_t len)
{
    uint16_t crc = 0;
    for(size_t i = 0; i < len; i++) {
        crc = (crc << 8) ^ crc16_table[((crc >> 8) ^ data[i]) & 0xFF];
    }
    return crc;
}

/* ============ 大端读写 ============ */
uint16_t rd_be16(const uint8_t * p) { return (uint16_t)((p[0] << 8) | p[1]); }
void     wr_be16(uint8_t * p, uint16_t v) { p[0] = (v >> 8) & 0xFF; p[1] = v & 0xFF; }
uint32_t rd_be32(const uint8_t * p) { return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | p[3]; }
void     wr_be32(uint8_t * p, uint32_t v) { p[0]=(v>>24)&0xFF; p[1]=(v>>16)&0xFF; p[2]=(v>>8)&0xFF; p[3]=v&0xFF; }

/* ============ 编码 ============ */
int frame_pack(uint8_t * buf, uint8_t type, uint32_t dev_id, uint16_t seq,
               const uint8_t * payload, size_t plen)
{
    if(plen > FRAME_MAX_PAYLOAD) return -1;

    size_t head_len = FRAME_HEAD_LEN;          /* 12 */
    size_t total    = head_len + plen;         /* 不含 crc */

    uint8_t * p = buf;
    wr_be16(p, FRAME_MAGIC);          p += 2;
    *p++ = FRAME_VER;
    wr_be16(p, (uint16_t)total);      p += 2;
    *p++ = type;
    wr_be32(p, dev_id);               p += 4;
    wr_be16(p, seq);                  p += 2;

    if(plen) memcpy(p, payload, plen);
    p += plen;

    /* CRC 覆盖整帧（total 字节） */
    uint16_t crc = crc16(buf, total);
    wr_be16(p, crc);
    p += 2;

    return (int)(total + FRAME_CRC_LEN);
}

/* ============ 解析 ============ */
int frame_parse(const uint8_t * frame, size_t flen,
                uint8_t * out_type, uint32_t * out_dev, uint16_t * out_seq,
                const uint8_t ** out_payload, size_t * out_plen)
{
    if(frame == NULL || flen < FRAME_HEAD_LEN + FRAME_CRC_LEN) return -1;

    /* magic 校验 */
    if(rd_be16(frame) != FRAME_MAGIC) return -1;

    /* 取 len（不含 crc，在偏移[3-4]），校验 flen 必须等于 len+2 */
    uint16_t len = rd_be16(frame + 3);
    if((size_t)len + FRAME_CRC_LEN != flen) return -1;
    if(len < FRAME_HEAD_LEN) return -1;

    /* CRC 校验 */
    uint16_t crc_stored = rd_be16(frame + len);
    uint16_t crc_calc  = crc16(frame, len);
    if(crc_stored != crc_calc) return -1;

    /* 偏移：magic[0-1] ver[2] len[3-4] type[5] dev_id[6-9] seq[10-11] */
    if(out_type)    *out_type = frame[5];
    if(out_dev)     *out_dev  = rd_be32(frame + 6);
    if(out_seq)     *out_seq  = rd_be16(frame + 10);

    size_t plen = len - FRAME_HEAD_LEN;
    if(out_payload) *out_payload = frame + FRAME_HEAD_LEN;
    if(out_plen)    *out_plen    = plen;

    return 0;
}
